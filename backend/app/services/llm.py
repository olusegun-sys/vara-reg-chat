"""
LLM interaction: build prompt from retrieved chunks, call the configured provider.

Why this file exists:
- Isolates "talking to an LLM" from HTTP routes, retrieval, and ingestion.
- The provider is chosen entirely by environment variables, so the same code
  runs locally, on Render, or with any OpenAI-compatible API (Groq, DeepSeek, OpenAI).
- The prompt is built here, not in routes, so we have one place to improve it.

Deployment note:
- No file paths, no local state, no writes. Pure function: chunks in, text out.
- Safe to run in any environment with outbound HTTPS.
"""

import json
from typing import List, Dict, Any
from openai import OpenAI

from app import config


# System prompt: the single most important piece of text in the app.
# Why so strict:
# - Compliance answers must be grounded in the document. No improvisation.
# - The exact refusal sentence is fixed so the frontend and tests can rely on it.
# - Citation requirement forces the LLM to anchor claims to pages.
SYSTEM_PROMPT = """You are a regulatory compliance assistant.
Answer the user's question using ONLY the context provided below.
Cite the page number and section for every claim you make.
If the answer is not contained in the context, respond exactly:
"I don't have that information in the provided document."

Be precise, concise, and never speculate."""


def _build_context(chunks: List[Dict[str, Any]]) -> str:
    """
    Format retrieved chunks into a labeled context block.

    Why the [Page X | Section Y] header:
    - It gives the LLM an explicit citation target.
    - It matches the citation format we return to the user, so answers and sources align.
    """
    parts = []
    for c in chunks:
        parts.append(f"[Page {c['page']} | {c['section']}]\n{c['text']}")
    return "\n\n---\n\n".join(parts)


def _build_user_message(question: str, chunks: List[Dict[str, Any]]) -> str:
    """Compose the full user turn: context block, then the question."""
    context = _build_context(chunks)
    return f"""CONTEXT:
{context}

QUESTION: {question}"""


def _get_client() -> OpenAI:
    """
    Create the provider client from environment config.

    Why not a module-level client:
    - Creating it per call is cheap and keeps this file free of import-time side effects.
    - Also makes tests easy: monkeypatch config values and call again.
    """
    return OpenAI(
        api_key=config.LLM_API_KEY,
        base_url=config.LLM_BASE_URL,
        timeout=60.0,  # avoid hanging forever if the provider stalls
    )


def generate_answer(question: str, chunks: List[Dict[str, Any]]) -> str:
    """
    Call the configured LLM and return the answer text.
    (Used for standard, non-streaming responses if needed elsewhere.)
    """
    if not chunks:
        return "I don't have that information in the provided document."

    client = _get_client()

    try:
        response = client.chat.completions.create(
            model=config.LLM_MODEL,
            temperature=config.LLM_TEMPERATURE,
            max_tokens=config.LLM_MAX_TOKENS,
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": _build_user_message(question, chunks)},
            ],
        )
    except Exception as exc:
        raise RuntimeError(f"LLM provider call failed: {exc}") from exc

    content = response.choices[0].message.content
    return (content or "").strip()


def stream_answer(question: str, chunks: List[Dict[str, Any]]):
    """
    Yields chunks of text and metadata for Server-Sent Events (SSE).
    
    Why this exists:
    - Waiting 5-10 seconds for the entire response to generate makes the app feel slow.
    - Streaming sends the text word-by-word as it is generated by the LLM, 
      mimicking the real-time typing effect of ChatGPT and DeepSeek.
    """
    if not chunks:
        yield f"data: {json.dumps({'type': 'text', 'text': 'I don\'t have that information in the provided document.'})}\n\n"
        return

    # 1. Send the sources metadata first so the UI can prepare the citation box
    sources_data = [
        {"page": c["page"], "section": c["section"], "document": c["document"]} 
        for c in chunks
    ]
    yield f"data: {json.dumps({'type': 'sources', 'sources': sources_data})}\n\n"

    client = _get_client()
    
    try:
        response = client.chat.completions.create(
            model=config.LLM_MODEL,
            temperature=config.LLM_TEMPERATURE,
            max_tokens=config.LLM_MAX_TOKENS,
            stream=True,  # THIS IS THE MAGIC SWITCH FOR FAST RESPONSES
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": _build_user_message(question, chunks)},
            ],
        )
        
        # 2. Yield the text chunks as they arrive
        for chunk in response:
            if chunk.choices and chunk.choices[0].delta.content:
                text = chunk.choices[0].delta.content
                yield f"data: {json.dumps({'type': 'text', 'text': text})}\n\n"
                
    except Exception as exc:
        error_msg = f"⚠️ LLM streaming error: {str(exc)}"
        yield f"data: {json.dumps({'type': 'text', 'text': error_msg})}\n\n"


def generate_title(question: str) -> str:
    """
    Ask the LLM to create a short 3-5 word title for the chat sidebar.

    Why a separate function:
    - Bypasses the strict RAG system prompt so the LLM can summarize intent.
    - Uses a smaller, faster model (llama-3.1-8b-instant) to prevent hitting
      the Groq rate limit while the main chat request is still processing.
    """
    client = _get_client()
    
    try:
        response = client.chat.completions.create(
            # Use a fast model for titles to avoid rate limits
            model="llama-3.1-8b-instant", 
            temperature=0.3, 
            max_tokens=20,   
            messages=[
                {"role": "system", "content": "You generate short 3-5 word titles for chat conversations. Output ONLY the title, no quotes, no punctuation, no markdown. Just the words."},
                {"role": "user", "content": f"Question: {question}"}
            ],
        )
        title = response.choices[0].message.content.strip()
        
        # Clean up any stray quotes or markdown the LLM might sneak in
        title = title.replace('"', '').replace("'", "").replace("*", "")
        
        if not title:
            return question[:30].strip() + "..." if len(question) > 30 else question
            
        return title

    except Exception as e:
        print(f"[title] LLM generation failed: {e}")
        return question[:30].strip() + "..." if len(question) > 30 else question